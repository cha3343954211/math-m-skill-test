SPECS={'L':{'name':'14米以上规格','min_len':14,'std':5},'M':{'name':'7-13.5米规格','min_len':7,'std':8},'S':{'name':'3-6.5米规格','min_len':3,'std':20}}

def fmt(x): return str(int(x)) if abs(x-int(x))<1e-9 else str(x)
def band(x): return f"{fmt(x)}-{fmt(x+0.4)}"
# Constructive feasible plan from long to short. This is a heuristic lower-bound plan used when exact 194-bundle CP proof is too slow.
avail={l:c for l,c in zip(lengths,counts)}
bundles=[]

def take(vals):
    for v in vals:
        if avail.get(v,0)<=0: raise RuntimeError(f'no {v} for pattern {vals}')
    for v in vals: avail[v]-=1

def add(spec, vals, n):
    for _ in range(n):
        take(vals)
        bundles.append({'spec':spec,'pieces':sorted(vals,reverse=True),'roots':len(vals),'total_length':round(sum(vals),1)})
# Manual pattern plan built to satisfy all constraints and use high lengths first; generated by balancing around 89m.
# L patterns (4/5 roots, all >=14)
for pat,n in [([25.5,22.5,20.5,20.0],1),([23.5,22.5,21.5,21.5],5),([22.5,22.0,22.0,22.0],3),([21.5,21.5,23.5,22.0],10),([21.0,21.0,23.5,23.5],6),([20.5,20.5,24.0,24.0],0),([20.0,20.0,24.5,24.5],0),([19.5,19.5,25.0,25.0],0),([19.0,19.0,25.5,25.5],0)]:
    if n: add('L',pat,n)
# Fallback algorithmic fill for remaining long stock: pair largest+smallest groups to 88.5-89.5
while sum(1 for v,c in avail.items() if v>=14 for _ in range(c))>=4:
    longs=[]
    stock=[v for v in lengths if v>=14 for _ in range(avail[v])]
    if len(stock)<4: break
    found=None
    # try 4-root combos from extremes
    arr=sorted(stock)
    for a in range(len(arr)):
      for b in range(a+1,len(arr)):
       for c in range(b+1,len(arr)):
        s3=arr[a]+arr[b]+arr[c]
        need_low=88.5-s3; need_high=89.5-s3
        for d in range(c+1,len(arr)):
            if need_low<=arr[d]<=need_high:
                found=[arr[a],arr[b],arr[c],arr[d]]; break
        if found: break
       if found: break
      if found: break
    if found is None: break
    add('L',found,1)
# M fill using >=7 pieces, prefer 7/8 roots
while True:
    stock=[v for v in lengths if v>=7 and avail[v]>0 for _ in range(avail[v])]
    if len(stock)<7: break
    arr=sorted(stock)
    found=None
    for r in [7,8]:
      # random-ish deterministic search combinations via recursion
      res=[]
      found_box=[None]
      def rec(start,k,total,chosen):
        if found_box[0]: return
        if k==0:
            if 88.5<=total<=89.5: found_box[0]=chosen.copy()
            return
        if start>=len(arr): return
        if total + sum(arr[start:start+k]) > 89.5: return
        if total + sum(arr[-k:]) < 88.5: return
        last=None
        for idx in range(start,len(arr)):
            if last==arr[idx]: continue
            last=arr[idx]
            chosen.append(arr[idx]); rec(idx+1,k-1,total+arr[idx],chosen); chosen.pop()
            if found_box[0]: return
      rec(0,r,0,[])
      found=found_box[0]
      if found: break
    if found is None: break
    add('M',found,1)
# S fill with remaining pieces >=3
while True:
    stock=[v for v in lengths if avail[v]>0 for _ in range(avail[v])]
    if len(stock)<19: break
    arr=sorted(stock)
    found=None
    for r in [19,20]:
      # greedily choose r around average 89/r
      # use DP by half-meter integer sums with counts
      target_range=[int(88.5*2), int(89*2), int(89.5*2)]
      dp={(0,0): []}
      for idx,v in enumerate(arr):
        u=int(round(v*2))
        for (k,s),lst in list(dp.items())[::-1]:
            if k<r and s+u<=179 and (k+1,s+u) not in dp:
                dp[(k+1,s+u)]=lst+[idx]
        for tar in target_range:
            if (r,tar) in dp:
                found=[arr[i] for i in dp[(r,tar)]]; break
        if found: break
      if found: break
    if found is None: break
    add('S',found,1)
# write outputs
